"use strict";
// Optional authoring tool. The committed HTML/JS/XML work without Node or a build.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const ROOT = path.resolve(__dirname, "..");
const escape = s => String(s).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
const plain = s => s.replace(/<!--[\s\S]*?-->/g, " ").replace(/<[^>]*>/g, " ").replace(/&#(x[\da-f]+|\d+);/gi, (_, n) => String.fromCodePoint(n[0].toLowerCase() === "x" ? parseInt(n.slice(1),16) : +n)).replace(/&(amp|lt|gt|quot|apos|nbsp);/g, (_, n) => ({amp:"&",lt:"<",gt:">",quot:'"',apos:"'",nbsp:" "}[n])).replace(/\s+/g," ").trim();
function plan(root = ROOT) {
  const context = {window:{}};
  vm.runInNewContext(fs.readFileSync(path.join(root,"js/posts-data.js"),"utf8"),context,{timeout:1000});
  const {SITE:site, POSTS:posts} = context.window;
  const fail = m => {throw new Error(m);};
  if (!site || !/^https:\/\/[^?#]+\/$/.test(site.url) || !site.title || !site.description) fail("SITE requires title, description and HTTPS URL ending in /");
  if (!Array.isArray(posts) || !posts.length) fail("POSTS must be a nonempty array");
  const ids = new Set(), urls = new Set(), files = new Map();
  const read = name => fs.readFileSync(path.join(root,name),"utf8");
  const dateValid = d => /^\d{4}-\d{2}-\d{2}$/.test(d) && Number.isFinite(Date.parse(d)) && new Date(d).toISOString().slice(0,10) === d;
  for (const p of posts) {
    for (const k of ["id","title","date","cat","excerpt","cover","url"]) if (typeof p[k] !== "string" || !p[k].trim()) fail(`invalid ${k}: ${p.id}`);
    if (!/^[a-z0-9-]+$/.test(p.id) || ids.has(p.id)) fail(`duplicate/unsafe id: ${p.id}`);
    if (!/^[a-z0-9-]+\.html$/.test(p.url) || urls.has(p.url)) fail(`duplicate/unsafe url: ${p.url}`);
    ids.add(p.id); urls.add(p.url);
    if (!dateValid(p.date)) fail(`invalid date: ${p.id}`);
    if (!Array.isArray(p.tags) || !p.tags.length || p.tags.some(t => typeof t !== "string" || !t.trim()) || new Set(p.tags).size !== p.tags.length) fail(`invalid tags: ${p.id}`);
    if (!["torii","magic","moon","scarlet","scroll"].includes(p.cover)) fail(`unknown cover: ${p.id}`);
    if (![p.words,p.mins].every(n => Number.isInteger(n) && n > 0) || (p.pin !== undefined && typeof p.pin !== "boolean")) fail(`invalid numeric/boolean field: ${p.id}`);
    const html = read(p.url);
    if (plain((html.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)||[])[1] || "") !== p.title) fail(`h1 differs from POSTS: ${p.url}`);
    if (!/<article\b[^>]*class="article-content"/.test(html)) fail(`missing article body: ${p.url}`);
  }
  const sorted = [...posts].sort((a,b)=>b.date.localeCompare(a.date)||a.id.localeCompare(b.id));
  const search = sorted.map(p => ({id:p.id,url:p.url,text:plain((read(p.url).match(/<article\b[^>]*class="article-content"[^>]*>([\s\S]*?)<\/article>/)||[])[1]||"")}));
  files.set("js/search-index.js", "// Generated by node tools/content.js --write; do not edit.\nwindow.SEARCH_INDEX = " + JSON.stringify(search,null,2).replace(/</g,"\\u003c") + ";\n");
  if (Buffer.byteLength(files.get("js/search-index.js")) > 100*1024) fail("search index exceeds 100 KiB budget");
  const absolute = name => new URL(name,site.url).href;
  files.set("rss.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom"><channel>\n<title>${escape(site.title)}</title><link>${escape(site.url)}</link><description>${escape(site.description)}</description><language>zh-CN</language>\n<atom:link href="${escape(absolute("rss.xml"))}" rel="self" type="application/rss+xml"/>\n${sorted.map(p=>`<item><title>${escape(p.title)}</title><link>${escape(absolute(p.url))}</link><guid isPermaLink="true">${escape(absolute(p.url))}</guid><pubDate>${new Date(p.date+"T00:00:00+08:00").toUTCString()}</pubDate><description>${escape(p.excerpt)}</description>${p.tags.map(t=>`<category>${escape(t)}</category>`).join("")}</item>`).join("\n")}\n</channel></rss>\n`);
  const pages = fs.readdirSync(root).filter(n=>n.endsWith(".html")).sort();
  files.set("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.filter(n=>n!=="404.html").map(n=>`<url><loc>${escape(absolute(n))}</loc>${posts.find(p=>p.url===n)?`<lastmod>${posts.find(p=>p.url===n).date}</lastmod>`:""}</url>`).join("\n")}\n</urlset>\n`);
  for (const name of pages) {
    let html = read(name);
    const post = posts.find(p=>p.url===name);
    if (/<article\b[^>]*class="article-content"/.test(html) && !post) fail(`unindexed article: ${name}`);
    const description = post ? post.excerpt : site.description;
    html = html.replace(/\s*<meta name="description"[^>]*\/>/, "");
    const metadata = `<!-- content:metadata -->\n  <meta name="description" content="${escape(description)}" />\n  ${name === "404.html" ? '<meta name="robots" content="noindex" />' : `<link rel="canonical" href="${escape(absolute(name))}" />`}\n  <link rel="alternate" type="application/rss+xml" title="${escape(site.title)} RSS" href="./rss.xml" />\n  <!-- /content:metadata -->`;
    // Strip our entire generated region before insertion, preserving author-owned markup.
    html = html.replace(/\s*<!-- content:metadata -->[\s\S]*?<!-- \/content:metadata -->/,"");
    html = html.replace(/<\/head>/, "  "+metadata+"\n</head>");
    if (post) {
      html = html.replace(/<title>[\s\S]*?<\/title>/,`<title>${escape(post.title)} · ${escape(site.title)}</title>`);
      const i=sorted.indexOf(post), older=sorted[i+1], newer=sorted[i-1];
      const link=(p,prev)=>p?`<a href="./${p.url}" data-${prev?"prev":"next"}><small>${prev?"← 上一篇（较早）":"下一篇（较新）→"}</small>${escape(p.title)}</a>`:`<span class="nav-empty${prev?"":" next"}" aria-disabled="true"><small>${prev?"← 上一篇（较早）":"下一篇（较新）→"}</small>已是${prev?"最早":"最新"}一篇</span>`;
      html=html.replace(/<nav class="post-nav"[\s\S]*?<\/nav>/,`<nav class="post-nav" aria-label="上下篇">\n    ${link(older,true)}\n    ${link(newer,false)}\n  </nav>`);
    }
    if (html.includes('./js/posts-data.js') && !html.includes('./js/search-index.js')) html=html.replace('<script src="./js/posts-data.js"></script>','<script src="./js/posts-data.js"></script>\n  <script src="./js/search-index.js"></script>');
    files.set(name,html);
  }
  return {files,posts,site};
}
function run(root=ROOT,write=false) {
  const {files,posts}=plan(root), stale=[];
  for(const [name,content] of files) {
    const target=path.join(root,name);
    if(!fs.existsSync(target)||fs.readFileSync(target,"utf8")!==content) {
      stale.push(name);
      if(write) fs.writeFileSync(target,content);
    }
  }
  if(stale.length&&!write) throw new Error(`stale content: ${stale.join(", ")}\nRun node tools/content.js --write and review the diff.`);
  console.log(`content ${write?"synced":"checked"}: ${posts.length} posts, ${files.size} artifacts${write?`, ${stale.length} updated`:""}`);
}
module.exports={plan,run,plain};
if(require.main===module) {try{run(ROOT,process.argv.includes("--write"));}catch(e){console.error(e.message);process.exitCode=1;}}
